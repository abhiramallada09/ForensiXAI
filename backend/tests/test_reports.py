def test_pdf_report_generation(setup_db: Session):
    db = setup_db
    c_num = f"CASE-REP-{uuid.uuid4().hex[:6]}"
    test_case = Case(
        case_number=c_num,
        name="Operation ReportLab - Forensic Examination Audit",
        investigator="A. Abhiram",
        status="Analysis Complete",
    )
    db.add(test_case)
    db.commit()

    base_time = datetime(2026, 11, 14, 16, 0, 0, tzinfo=timezone.utc)

    # 1. Add Evidence
    ev = Evidence(
        case_id=test_case.id,
        evidence_number="EVD-001",
        filename="kernel_memory.raw",
        stored_path="/evidence/kernel_memory.raw",
        file_type="Memory Dump",
        file_size_bytes=2147483648,
        sha256="aa" * 32,
        classification="OBSERVED",
        status="Uploaded",
    )
    db.add(ev)

    # 2. Add Deleted File
    df = DeletedFileRecord(
        case_id=test_case.id,
        filename="exfil_stager.exe",
        original_path="C:\\Users\\Victim\\AppData\\Local\\Temp\\exfil_stager.exe",
        carved_header_signature="4D 5A 90 00",
        file_type="PE Executable",
        estimated_size_bytes=45056,
        confidence=0.92,
        classification="SUSPICIOUS",
        status="Probable deleted artifact",
        corroborating_sources=["MFT Residue", "Volatility Closed Handles"],
        reconstruction_reason="Correlated memory handle residue and command-line deletion traces",
    )
    db.add(df)

    # 3. Add Timestamp Window
    tw = TimestampReconstructionRecord(
        case_id=test_case.id,
        event_title="Process Infiltration Window",
        observed_timestamp=base_time,
        probable_window_start=base_time - timedelta(seconds=20),
        probable_window_end=base_time + timedelta(seconds=15),
        probable_event_time=base_time,
        window_duration_seconds=35.0,
        consistency_status="CONSISTENT",
        classification="RECONSTRUCTED",
        confidence=0.94,
        sources_compared=[{"source": "MACB"}, {"source": "Volatility pslist"}],
        related_event_ids=[],
        reconstruction_reason="Correlated process start and file touch within 35s window",
    )
    db.add(tw)

    # 4. Add Anti-Forensic Indicator
    af = AntiForensicIndicatorRecord(
        case_id=test_case.id,
        indicator_type="Audit Log Cleared",
        title="Anti-Forensic Log Cleansing Detected",
        severity="Critical",
        confidence=0.96,
        classification="SUSPICIOUS",
        supporting_evidence_ids=[],
        supporting_artifacts=["Security Event ID 1102"],
        reason="Possible manipulation detected: Security audit log was intentionally cleared.",
        recommendation="Inspect unallocated space and VSS shadow copies.",
    )
    db.add(af)

    # 5. Add Cloud Record
    cr = CloudEvidenceRecord(
        case_id=test_case.id,
        provider="AWS",
        event_time=base_time + timedelta(minutes=2),
        event_name="StopLogging",
        service_name="cloudtrail.amazonaws.com",
        identity_arn="arn:aws:iam::123456:user/infiltrator",
        source_ip="198.51.100.22",
        classification="SUSPICIOUS",
        severity="Critical",
        is_anti_forensic=True,
        raw_payload={"eventName": "StopLogging"},
        notes="Possible anti-forensic manipulation: CloudTrail logging halted.",
    )
    db.add(cr)
    db.commit()

    # Generate PDF in memory
    pdf_bytes = generate_case_pdf_report(test_case.id, db)
    assert pdf_bytes is not None
    assert len(pdf_bytes) > 5000, f"Expected PDF > 5KB, got {len(pdf_bytes)} bytes"
    assert pdf_bytes.startswith(b"%PDF-"), "Generated bytes must be valid PDF header"


def test_reports_rest_api(setup_db: Session):
    db = setup_db
    c_num = f"CASE-REP-API-{uuid.uuid4().hex[:6]}"
    test_case = Case(
        case_number=c_num,
        name="Report API Endpoint Test",
        investigator="A. Abhiram",
        status="Analysis Complete",
    )
    db.add(test_case)
    db.commit()

    # Test GET /reports/summary
    res_summary = client.get(f"/api/v1/cases/{test_case.id}/reports/summary")
    assert res_summary.status_code == 200
    summary_data = res_summary.json()
    assert summary_data["case_number"] == c_num
    assert "evidentiary_standards" in summary_data

    # Test GET /reports/pdf (Streaming PDF)
    res_pdf = client.get(f"/api/v1/cases/{test_case.id}/reports/pdf")
    assert res_pdf.status_code == 200
    assert res_pdf.headers.get("content-type") == "application/pdf"
    assert "attachment;" in res_pdf.headers.get("content-disposition", "")
    assert "X-Report-SHA256" in res_pdf.headers
    assert res_pdf.content.startswith(b"%PDF-")

    # Test POST /reports/generate (File Generation)
    res_gen = client.post(f"/api/v1/cases/{test_case.id}/reports/generate")
    assert res_gen.status_code == 200
    gen_data = res_gen.json()
    assert gen_data["status"] == "generated"
    assert os.path.exists(gen_data["file_path"])
    assert gen_data["file_size_bytes"] > 5000
